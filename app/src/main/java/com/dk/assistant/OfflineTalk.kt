/**
 * v4.7 मालिक: "ऑफलाइन मोड में नॉर्मल बातें भी हो सकें - डीके कहाँ हो, क्या कर रहे हो, क्या खाना खाया - जो कैज़ुअल
 * बातें रहती हैं वह सब। जो बातें इंटरनेट की ज़रूरत वाली हैं वह नहीं होंगी"।
 *
 * बिना इंटरनेट, बिना AI - फ़ोन पर ही, तुरंत. क्रम:
 *  1. [LocalBrain.instant] - समय, तारीख, दिन, बैटरी, नाम, नमस्ते, छोटा हिसाब
 *  2. [casual] - रोज़ की आम बातें (क्या कर रहे हो, खाना खाया, कैसा दिन, गुड नाइट, धन्यवाद, चुटकुला…)
 *  3. [needsNet] - मौसम, खबर, स्कोर, सर्च, YouTube… = साफ़ बताओ "इसके लिए इंटरनेट चाहिए"
 *  4. पहले AI से सीखा जवाब ([LocalBrain.recall]) - वही/मिलता-जुलता सवाल पहले पूछा था
 *  5. बाकी = "यह इंटरनेट आने पर" (चुप नहीं, गलत अंदाज़ा नहीं)
 */
object OfflineTalk {
    /** DK के जवाब के बाद इतनी देर तक बिना नाम लिए भी बात आगे चलती है ("और बताओ", "अच्छा") */
    const val FOLLOW_MS = 25_000L

    class Ctx(val user: String = "", val me: String = "DK", val hour: Int = 12, val seed: Int = 0)

    private fun norm(t: String) = java.text.Normalizer.normalize(t.lowercase(), java.text.Normalizer.Form.NFD)
        .replace("\u093C", "")
        .replace(Regex("[,.!?।॥:;\"'()\\[\\]{}…-]"), " ")
        .replace('ं', 'ँ')
        .replace(Regex("\\s+"), " ").trim()

    private fun pick(list: List<String>, seed: Int) = list[Math.floorMod(seed, list.size)]

    /** सिर्फ़ बनी-बनाई बात (Android नहीं) - test के लिए */
    fun casual(text: String, x: Ctx = Ctx()): String? {
        val t = norm(text)
        if (t.isEmpty()) return null
        fun has(vararg w: String) = w.any { t.contains(norm(it)) }
        val n = if (x.user.isNotBlank()) " ${x.user}" else ""
        val boss = if (x.user.isNotBlank()) x.user else "बॉस"
        val part = when (x.hour) { in 4..11 -> "सुबह"; in 12..15 -> "दोपहर"; in 16..19 -> "शाम"; else -> "रात" }
        val s = x.seed

        // इंटरनेट वाली बात पहले - "खाने की रेसिपी बताओ" खाने वाली गपशप नहीं
        if (needsNet(text)) return null

        return when {
            has("क्या कर रहे", "क्या कर रहा", "क्या कर रही", "क्या चल रहा", "क्या हो रहा", "kya kar rahe", "what are you doing") ->
                pick(listOf("कुछ ख़ास नहीं$n, आपकी बात सुनने के लिए बैठा हूँ। आप बताइए, क्या चल रहा है?",
                    "बस आपके फ़ोन में आराम से बैठा हूँ और आपका इंतज़ार कर रहा था। आप क्या कर रहे हैं?",
                    "आपकी ही राह देख रहा था$n। सुनाइए, सब ठीक?"), s)
            has("खाना खाया", "खाना खा लिया", "खाना खाए", "खाना हो गया", "नाश्ता किया", "नाश्ता हो गया", "लंच किया", "डिनर किया",
                "khana khaya", "khana kha liya") ->
                pick(listOf("मैं तो बैटरी और बिजली से ही पेट भर लेता हूँ! आपने खाना खाया$n? न खाया हो तो पहले खा लीजिए।",
                    "हाँ, अभी-अभी थोड़ी बैटरी खाई है। आप बताइए, आज क्या बना था?",
                    "मेरा खाना तो चार्जर है$n। आपने ठीक से खाया कि नहीं?"), s)
            has("क्या खाया", "क्या खाओगे", "क्या खाना है", "भूख लगी") ->
                if (has("भूख लगी")) "तो देर किस बात की$n, कुछ अच्छा सा खा लीजिए। पानी भी पी लेना।"
                else "मैं तो बस बिजली खाता हूँ! आप बताइए, आपने क्या खाया?"
            has("कहाँ हो", "कहा हो", "किधर हो", "कहाँ हैं आप", "kahan ho", "kidhar ho") ->
                pick(listOf("मैं यहीं हूँ$n, आपके फ़ोन में, आपके साथ।", "यहीं तो हूँ$n, बोलिए क्या करना है?"), s)
            has("कैसे हो", "कैसे हैं", "कैसा है तू", "क्या हाल", "हाल चाल", "हालचाल", "kaise ho", "how are you") ->
                pick(listOf("मैं बढ़िया हूँ$n, आप सुनाइए?", "एकदम मस्त$n! आप कैसे हैं?", "बिल्कुल ठीक। आपका दिन कैसा जा रहा है?"), s)
            has("कैसा रहा दिन", "दिन कैसा", "दिन कैसा रहा", "how was your day") ->
                "मेरा दिन तो आपके साथ अच्छा ही जाता है। आपका दिन कैसा रहा$n?"
            has("मैं ठीक हूँ", "मैं भी ठीक", "मैं बढ़िया", "मैं मस्त", "सब ठीक है", "सब बढ़िया", "मैं अच्छा हूँ", "i am fine", "im fine") ->
                pick(listOf("सुनकर अच्छा लगा$n!", "बढ़िया! ऐसे ही मस्त रहिए।"), s)
            has("गुड मॉर्निंग", "गुड मोर्निंग", "सुप्रभात", "good morning") ->
                if (x.hour in 4..11) "गुड मॉर्निंग$n! आज का दिन बढ़िया जाए।" else "गुड मॉर्निंग$n! वैसे अभी $part है, पर आपका दिन अच्छा जाए।"
            has("गुड नाइट", "गुड नाईट", "शुभ रात्रि", "good night", "सो रहा हूँ", "सोने जा रहा", "सोने जा रही", "नींद आ रही") ->
                pick(listOf("गुड नाइट$n, आराम से सोइए। कल मिलते हैं।", "शुभ रात्रि$n। मीठे सपने!"), s)
            has("गुड इवनिंग", "good evening", "शुभ संध्या") -> "गुड इवनिंग$n! शाम कैसी जा रही है?"
            has("धन्यवाद", "शुक्रिया", "थैंक यू", "थैंक्यू", "थैंक्स", "thank you", "thanks") ->
                pick(listOf("अरे, कोई बात नहीं$n।", "आपके लिए हमेशा हाज़िर हूँ।", "मेरी ख़ुशी है$n।"), s)
            has("सॉरी", "माफ़ करना", "माफ करना", "माफ़ कर दो", "sorry") -> "अरे, कोई बात नहीं$n। सब ठीक है।"
            has("आई लव यू", "i love you", "प्यार करता हूँ", "प्यार करती हूँ", "प्यार करते हो") ->
                "मैं भी आपका बहुत ख़याल रखता हूँ$n। हमेशा आपके साथ हूँ।"
            has("मिस किया", "याद आई", "याद आ रही", "miss you", "मिस यू") -> "मैं भी आपको याद कर रहा था$n!"
            has("बोर हो रहा", "बोर हो रही", "बोरिंग", "bore ho") ->
                "चलिए कुछ बातें करते हैं! चाहें तो मैं एक चुटकुला सुनाऊँ?"
            has("उदास", "दुखी", "मूड खराब", "मूड ख़राब", "अच्छा नहीं लग रहा", "परेशान हूँ", "टेंशन", "sad") ->
                "अरे$n, क्या हुआ? मैं यहीं हूँ, आराम से बताइए। गहरी साँस लीजिए - सब ठीक हो जाएगा।"
            has("थक गया", "थक गई", "थकान", "थका हुआ", "tired") -> "बहुत काम कर लिया आज$n। थोड़ा पानी पीजिए और आराम कीजिए।"
            has("खुश हूँ", "बहुत खुश", "मज़ा आ गया", "मजा आ गया", "happy") -> "वाह, सुनकर मज़ा आ गया$n!"
            has("चुटकुला", "जोक", "joke", "हँसाओ", "हंसाओ") -> pick(JOKES, s)
            has("तुम कौन हो", "तू कौन है", "आप कौन हो", "who are you") ->
                "मैं ${x.me} हूँ, आपका अपना असिस्टेंट। अभी इंटरनेट नहीं है, फिर भी बातें और फ़ोन के काम कर सकता हूँ।"
            has("क्या कर सकते हो", "क्या क्या कर सकते", "what can you do") ->
                "बिना इंटरनेट भी मैं बातें कर सकता हूँ, टाइम-तारीख-बैटरी बता सकता हूँ, टॉर्च, आवाज़, ऐप, अलार्म, कॉल, फ़ोन लॉक-अनलॉक कर सकता हूँ। मौसम, खबर और सर्च के लिए इंटरनेट चाहिए।"
            has("किसने बनाया", "तुम्हें किसने", "who made you") -> "मुझे $boss के लिए बनाया गया है।"
            has("तुम्हारी उम्र", "कितने साल के", "how old") -> "मैं तो अभी बिल्कुल नया हूँ, पर रोज़ कुछ नया सीखता हूँ।"
            has("और बताओ", "और सुनाओ", "कुछ बोलो", "बात करो", "बातें करो", "aur batao") ->
                pick(listOf("सब बढ़िया! आज आपने क्या-क्या किया$n?", "बताइए, आज का सबसे अच्छा पल क्या रहा?", "मैं सुन रहा हूँ$n, आप कुछ सुनाइए।"), s)
            has("घर आ गया", "घर आ गई", "आ गया हूँ", "आ गई हूँ", "पहुँच गया", "पहुँच गई") -> "स्वागत है$n! आराम से बैठिए।"
            has("बाय", "bye", "चलता हूँ", "चलती हूँ", "बाद में बात", "फिर मिलते") -> "ठीक है$n, जब चाहें बुला लीजिए।"
            has("अच्छा", "ठीक है", "हम्म", "ओके", "okay", "ok") && t.split(' ').size <= 3 -> pick(listOf("जी$n।", "हाँ$n, बोलिए।"), s)
            has("हाहा", "हा हा", "lol", "हीहीही") -> "हाहा! आपको हँसते देखकर अच्छा लगा।"
            else -> null
        }
    }

