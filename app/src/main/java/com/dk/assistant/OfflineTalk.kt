    /** यह बात इंटरनेट / AI के बिना नहीं हो सकती */
    fun needsNet(text: String): Boolean {
        val t = norm(text)
        return NET.any { t.contains(norm(it)) }
    }

    const val NEED_NET = "इसके लिए इंटरनेट चाहिए। नेट आते ही पूछिए, बता दूँगा। तब तक बातें और फ़ोन के काम बिना नेट भी कर सकता हूँ।"
    const val DONT_KNOW = "अभी इंटरनेट नहीं है, तो इसका पक्का जवाब नहीं दे पाऊँगा। नेट आने पर पूछिए। तब तक आम बातें और फ़ोन के काम चालू हैं।"

