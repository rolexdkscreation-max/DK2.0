    )

    /**
     * ऑफलाइन में बात का जवाब (Android). null = कहने लायक कुछ नहीं (चुप रहो).
     * @param addressed DK का नाम लिया / मालिक की आवाज़ / चलती बातचीत - तभी "पता नहीं" वाला जवाब भी देते हैं
     */
    fun reply(c: Context, text: String, addressed: Boolean): String? {
        val t = text.trim()
        if (t.isEmpty()) return null
        if (needsNet(t)) return if (addressed) NEED_NET else null
        try { LocalBrain.instant(c, t) }  catch (_: Exception) { null }?.let { return it }
        val x = Ctx(Prefs.userName(c), Prefs.assistantName(c), Calendar.getInstance().get(Calendar.HOUR_OF_DAY), (System.nanoTime() / 1000).toInt())
        casual(t, x)?.let { return it }
        if (!addressed) return null
        try { LocalBrain.recall(c, t, exact = false) } catch (_: Exception) { null }?.let { return it }
        return DONT_KNOW
    }
